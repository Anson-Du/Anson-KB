def add_summary(text):
    """要点条目：▍ 前缀，首句（到第一个中文冒号）加粗深蓝"""
    p = doc.add_paragraph()
    p.paragraph_format.space_after = Pt(6)
    p.paragraph_format.left_indent = Cm(0.5)
    p.paragraph_format.first_line_indent = Cm(-0.5)
    head = '▍'
    run0 = p.add_run(head)
    run0.font.size = Pt(11)
    run0.font.bold = True
    run0.font.color.rgb = COLOR_HEADING
    run0.font.name = '微软雅黑'
    run0.element.rPr.rFonts.set(qn('w:eastAsia'), '微软雅黑')
    if '：' in text:
        lead, rest = text.split('：', 1)
        r1 = p.add_run(lead + '：')
        r1.font.size = Pt(11)
        r1.font.bold = True
        r1.font.color.rgb = COLOR_HEADING
        r1.font.name = '微软雅黑'
        r1.element.rPr.rFonts.set(qn('w:eastAsia'), '微软雅黑')
        body = rest
    else:
        body = text
    r2 = p.add_run(body)
    r2.font.size = Pt(11)
    r2.font.color.rgb = COLOR_NORMAL
    r2.font.name = '微软雅黑'
    r2.element.rPr.rFonts.set(qn('w:eastAsia'), '微软雅黑')


